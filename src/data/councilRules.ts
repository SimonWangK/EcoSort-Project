export function normaliseCouncil(council?: string | null): SupportedCouncil {
  const match = SUPPORTED_COUNCILS.find((item) => item === council);
  return match || DEFAULT_COUNCIL;
}

export function getRulesForCouncil(council?: string | null): CouncilRule[] {
  const activeCouncil = normaliseCouncil(council);
  return COUNCIL_RULES.filter((rule) => rule.council === activeCouncil);
}

export function getQuickItemsForCouncil(council?: string | null): string[] {
  const items = getRulesForCouncil(council).map((rule) => rule.item);
  return Array.from(new Set(items)).slice(0, 8);
}

export function getCouncilRuleSummary(council?: string | null): string {
  const activeCouncil = normaliseCouncil(council);
  const count = getRulesForCouncil(activeCouncil).length;
  return `${activeCouncil} · ${count} rules · reviewed ${reviewedAt}`;
}

