export interface ReverseGeocodeLike {
  city?: string | null;
  district?: string | null;
  subregion?: string | null;
  region?: string | null;
  name?: string | null;
  street?: string | null;
  postalCode?: string | null;
}

export function resolveCouncilFromAddress(address?: ReverseGeocodeLike | null): SupportedCouncil | null {
  if (!address) return null;
  const text = [address.city, address.district, address.subregion, address.region, address.name, address.street, address.postalCode]
    .filter(Boolean)
    .join(' ')
    .toLowerCase();

  if (/merri[- ]?bek|moreland|brunswick|coburg|fawkner|pascoe vale|glenroy|hadfield/.test(text)) return 'Merri-bek City Council';
  if (/yarra|richmond|fitzroy|collingwood|abbotsford|carlton north|clifton hill|fairfield/.test(text)) return 'Yarra Council';
  if (/melbourne|cbd|docklands|southbank|north melbourne|west melbourne|parkville|kensington/.test(text)) return 'Melbourne City Council';
  return null;
}

export function resolveCouncilFromCoordinates(latitude: number, longitude: number): SupportedCouncil {
  // Lightweight geofence fallback for the supported councils. A production app
  // could replace this with official GIS boundaries or a council lookup API.
  const inMerriBek = latitude >= -37.78 && latitude <= -37.68 && longitude >= 144.90 && longitude <= 145.05;
  const inYarra = latitude >= -37.84 && latitude <= -37.76 && longitude > 144.98 && longitude <= 145.06;
  const inMelbourne = latitude >= -37.86 && latitude <= -37.76 && longitude >= 144.90 && longitude <= 145.00;

  if (inMerriBek) return 'Merri-bek City Council';
  if (inYarra) return 'Yarra Council';
  if (inMelbourne) return 'Melbourne City Council';
  return DEFAULT_COUNCIL;
}
